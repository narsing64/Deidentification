"""Download the TEST (held-out) or VALIDATION (development) split of gretelai/gretel-pii-masking-en-v1
(Apache-2.0, fully synthetic) through the Hugging Face dataset-viewer API (JSON pages of 100 rows; no extra
packages needed).

    python scripts/fetch_gretel_test.py                       -> data/external/gretel_pii_en_v1/test.jsonl
    python scripts/fetch_gretel_test.py --split validation    -> .../validation.jsonl (development data)

Nothing in this project is trained on either split. Rule decisions may use `validation`, never `test`.
"""
from __future__ import annotations

import json
import time
import urllib.parse
import urllib.request

from deid.config import resolve_path

DATASET = "gretelai/gretel-pii-masking-en-v1"
API = "https://datasets-server.huggingface.co/rows?dataset={ds}&config=default&split={split}&offset={off}&length=100"


def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--split", default="test", choices=["test", "validation"])
    split = ap.parse_args(argv).split
    out_dir = resolve_path("data/external/gretel_pii_en_v1")
    out_dir.mkdir(parents=True, exist_ok=True)
    rows, total, off = [], None, 0
    while total is None or off < total:
        url = API.format(ds=urllib.parse.quote(DATASET, safe=""), split=split, off=off)
        for attempt in range(8):
            try:
                with urllib.request.urlopen(url, timeout=60) as r:
                    page = json.load(r)
                break
            except Exception:  # rate limit (HTTP 429) or network hiccup: back off and retry
                if attempt == 7:
                    raise
                time.sleep(10 * (attempt + 1))
        total = page["num_rows_total"]
        rows += [x["row"] for x in page["rows"]]
        off += 100
        time.sleep(1.5)  # stay well under the API rate limit
    with open(out_dir / f"{split}.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    (out_dir / f"SOURCE.{split}.md").write_text(
        f"# Source\n\n- Dataset: https://huggingface.co/datasets/{DATASET}\n- Licence: Apache-2.0 (dataset card)\n"
        f"- Content: fully synthetic documents generated by Gretel Navigator (no real people)\n"
        f"- Fetched: {time.strftime('%Y-%m-%d')} via the dataset-viewer API, split={split}; rows: {len(rows)}\n",
        encoding="utf-8")
    print(f"saved {len(rows)} rows to {out_dir / (split + '.jsonl')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
